        "T": ["#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#.."],
        "U": ["#...#", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."],
        "V": ["#...#", "#...#", "#...#", "#...#", "#...#", ".#.#.", "..#.."],
        "W": ["#...#", "#...#", "#...#", "#.#.#", "#.#.#", "#.#.#", ".#.#."],
        "X": ["#...#", "#...#", ".#.#.", "..#..", ".#.#.", "#...#", "#...#"],
        "Y": ["#...#", "#...#", ".#.#.", "..#..", "..#..", "..#..", "..#.."],
        "Z": ["#####", "....#", "...#.", "..#..", ".#...", "#....", "#####"],
        ":": [".", ".", "#", ".", "#", ".", "."],
        ".": [".", ".", ".", ".", ".", ".", "#"],
        "+": [".....", "..#..", "..#..", "#####", "..#..", "..#..", "....."],
        "-": [".....", ".....", ".....", "#####", ".....", ".....", "....."],
        " ": ["...", "...", "...", "...", "...", "...", "..."],
    ]

    /// Uppercases and strips accents ("São Paulo" -> "SAO PAULO") so text maps onto the glyph set.
    public static func normalize(_ text: String) -> String {
        text.folding(options: [.diacriticInsensitive, .caseInsensitive], locale: Locale(identifier: "en_US"))
            .uppercased()
    }

    /// Rows of on/off dots for a character. Lowercase maps to uppercase; unknown characters render as a space.
    public static func glyph(for character: Character) -> [[Bool]] {
        let pattern = patterns[character] ?? patterns[Character(character.uppercased())] ?? patterns[" "]!
        return pattern.map { row in row.map { $0 == "#" } }
    }

    public static func width(of character: Character) -> Int {
        glyph(for: character).first?.count ?? 0
    }

    /// Total columns for a string, with `gap` blank columns between glyphs.
    public static func columns(for text: String, gap: Int = 1) -> Int {
        guard !text.isEmpty else { return 0 }
        return text.reduce(0) { $0 + width(of: $1) } + gap * (text.count - 1)
    }
}
